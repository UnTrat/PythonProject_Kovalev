#Посчитать и вывести количество элементов арифметической прогрессии,
#удовлетворяющих условию 10<ai<30.
n = int(input("Укажите шаг арифметической прогрессии: "))
ai = 1
b = 0
while ai < 31:
    ai += n
    if 10<ai<30:
        b += 1
print("элементов арифметической прогрессии, удовлетворяющих условию: ",b)
